-- Схема аналітичного сховища CityFlow (dwh) та допоміжний простір завантаження змін (warehouse_input)
CREATE SCHEMA IF NOT EXISTS dwh;
CREATE SCHEMA IF NOT EXISTS warehouse_input;

CREATE TABLE IF NOT EXISTS dwh.dim_customer (
    customer_key bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id text NOT NULL,
    full_name text NOT NULL,
    city text,
    valid_from timestamptz NOT NULL,
    valid_to timestamptz,
    is_current boolean NOT NULL,
    UNIQUE (customer_id, valid_from),
    CHECK (valid_to IS NULL OR valid_to > valid_from),
    CHECK (is_current = (valid_to IS NULL))
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_dim_customer_current
    ON dwh.dim_customer (customer_id) WHERE is_current;

CREATE TABLE IF NOT EXISTS dwh.dim_merchant (
    merchant_key bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    merchant_id text NOT NULL UNIQUE,
    merchant_name text NOT NULL,
    city text
);

CREATE TABLE IF NOT EXISTS dwh.dim_product (
    product_key bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id text NOT NULL UNIQUE,
    merchant_id text NOT NULL,
    product_name text NOT NULL,
    unit_price_uah numeric(12, 2) NOT NULL,
    is_active boolean NOT NULL,
    source_version_at timestamptz NOT NULL DEFAULT '-infinity'
);

CREATE TABLE IF NOT EXISTS dwh.dim_date (
    date_key date PRIMARY KEY,
    calendar_year integer NOT NULL,
    calendar_month integer NOT NULL CHECK (calendar_month BETWEEN 1 AND 12),
    day_of_month integer NOT NULL CHECK (day_of_month BETWEEN 1 AND 31)
);

CREATE TABLE IF NOT EXISTS dwh.fact_orders (
    order_id text PRIMARY KEY,
    customer_key bigint NOT NULL REFERENCES dwh.dim_customer,
    merchant_key bigint NOT NULL REFERENCES dwh.dim_merchant,
    date_key date NOT NULL REFERENCES dwh.dim_date,
    created_at timestamptz NOT NULL,
    order_status text NOT NULL,
    currency text NOT NULL,
    subtotal_amount numeric(12, 2) NOT NULL,
    delivery_fee numeric(12, 2) NOT NULL,
    discount_amount numeric(12, 2) NOT NULL,
    total_amount numeric(12, 2) NOT NULL,
    warehouse_modified_at timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS dwh.fact_order_items (
    order_item_id text PRIMARY KEY,
    order_id text NOT NULL REFERENCES dwh.fact_orders,
    customer_key bigint NOT NULL REFERENCES dwh.dim_customer,
    merchant_key bigint NOT NULL REFERENCES dwh.dim_merchant,
    product_key bigint NOT NULL REFERENCES dwh.dim_product,
    date_key date NOT NULL REFERENCES dwh.dim_date,
    quantity integer NOT NULL CHECK (quantity > 0),
    unit_price numeric(12, 2) NOT NULL,
    line_discount numeric(12, 2) NOT NULL,
    line_total numeric(12, 2) NOT NULL,
    currency text NOT NULL
);